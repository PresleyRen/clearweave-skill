#!/usr/bin/env python3
"""Render bounded capability documentation. Default checks; --write updates known docs."""
from __future__ import annotations
import argparse
from collections import Counter
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
START = '<!-- capabilities:start -->'
END = '<!-- capabilities:end -->'


def load(path: str):
    return json.loads((ROOT / path).read_text(encoding='utf-8'))


def capability_table(catalog: dict, zh: bool, prefix: str = '') -> str:
    headings = ('能力编号与名称','执行方式','规则位置') if zh else ('Capability','Implementation','Rule location')
    lines = ['| ' + ' | '.join(headings) + ' |','| --- | --- | --- |']
    for row in catalog['capabilities']:
        name = row['name_zh'] if zh else row['name_en']
        target = prefix+'skills/clearweave/'+row['module']+'#'+row['anchor']
        lines.append(f"| **{row['id']}** {name} | `{row['kind']}` | [{row['module']}]({target}) |")
    return '\n'.join(lines)


def document(catalog: dict, sources: list, features: list) -> str:
    lines = ['# Capability and conflict atlas / 能力与冲突定位图', '',
             'Generated by `python tools/render_catalog.py --write`. Edit the catalog, not this generated table.', '',
             '**Scope:** all 32 entries and 194 documented decisions in this project’s source audit. This is not a census of every upstream subfile or an assertion that 32 original skills were executed.', '',
             '`host` means model instructions, not a deterministic guarantee; `literal` is limited string comparison; `candidate` is a lexical risk warning; `script` is implemented Python; `workflow` is a procedure; `package` is a portable folder format.', '',
             capability_table(catalog, False, '../'), '', '## Capability boundaries / 能力边界', '']
    for cap in catalog['capabilities']:
        lines.extend([f"### {cap['id']} · {cap['name_zh']}",cap['implementation_boundary'],
                      f"Sources: {', '.join(cap['sources'])}. Scenarios: {', '.join(cap['cases'])}.",''])
    lines += ['## 26 conflicts / 26 类冲突', '',
              'Each pair has one English and one Chinese authored fixture. A constraint check is not an independent model-writing experiment.', '',
              '| ID | Conflict / 冲突 | Capability route | Case IDs |','| --- | --- | --- | --- |']
    for c in catalog['conflicts']:
        lines.append(f"| {c['id']} | {c['name_en']} / {c['name_zh']} | {', '.join(c['capabilities'])} | {', '.join(c['cases'])} |")
    lines += ['', '## Source coverage / 32 项来源覆盖', '',
              'A = adopted decision statements. D = adapted or excluded decision statements. These are not 194 distinct algorithms. Expand exact decisions with `python tools/coverage.py --source S01`.', '',
              '| Source | Audit A / D | Capability families |','| --- | --- | --- |']
    for src in sources:
        caps=sorted({c for f in features if f['source']==src['id'] for c in f['capabilities']})
        lines.append(f"| [{src['id']} {src['repo']}]({src['url']}) | {len(src['adopted'])} / {len(src['rejected_or_modified'])} | {', '.join(caps)} |")
    lines += ['', '## Extension / 扩展', '',
              'Use [maintenance](../skills/clearweave/references/maintenance.md) and the [source decision map](feature-map.json). A source link is inspiration, not endorsement or proof of effectiveness.', '',
              'Feature mappings are keyword-assisted, manually reviewable crosswalks. Scenario links cover a capability family; they do not independently test every clause of every source decision. Add narrower regression cases when a real failure exposes a gap.', '']
    return '\n'.join(lines)


def expected_documents() -> dict[str, str]:
    cat=load('skills/clearweave/assets/capabilities.json')
    sources=load('docs/source-audit.json')['sources']
    features=load('docs/feature-map.json')['features']
    output={'docs/capabilities.md':document(cat,sources,features)}
    for filename,zh in [('README.md',False),('README.zh-CN.md',True)]:
        text=(ROOT/filename).read_text(encoding='utf-8')
        if text.count(START)!=1 or text.count(END)!=1:
            raise ValueError(f'Exactly one capability marker pair required: {filename}')
        before,tail=text.split(START,1);_,after=tail.split(END,1)
        output[filename]=before+START+'\n'+capability_table(cat,zh)+'\n'+END+after
    return output


def stale_documents() -> list[str]:
    return [path for path,expected in expected_documents().items()
            if not (ROOT/path).is_file() or (ROOT/path).read_text(encoding='utf-8')!=expected]


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true',help='Update generated sections and atlas')
    args=parser.parse_args()
    try:
        expected=expected_documents()
        stale=stale_documents()
        if args.write:
            for path in stale:(ROOT/path).write_text(expected[path],encoding='utf-8')
            print(f'Updated {len(stale)} documentation files.');return 0
        if stale:
            print('Stale generated documentation: '+', '.join(stale),file=sys.stderr);return 1
        print('Generated capability tables and atlas are current.');return 0
    except (OSError,ValueError,KeyError,TypeError) as exc:
        print(f'render-catalog: {exc}',file=sys.stderr);return 2

if __name__=='__main__':raise SystemExit(main())
